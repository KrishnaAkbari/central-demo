// Build a regex-valid email check. Pragmatic, not RFC-perfect — catches
// the common typos (missing @, missing TLD, double dots) without rejecting
// edge cases. Use with .test() in form validation.
export function isValidEmail(value) {
  if (typeof value !== 'string') return false
  const trimmed = value.trim()
  if (trimmed.length === 0) return false
  return /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(trimmed)
}
